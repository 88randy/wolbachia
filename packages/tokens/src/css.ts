/**
 * Renders the tokens as CSS custom properties for the web.
 * Pure functions: `scripts/build-css.ts` only writes the result to disk.
 */
import { font, formatShadow, radius, shadow, spacing } from "./scales.ts";
import { darkTheme, lightTheme } from "./themes.ts";
import type { Theme } from "./themes.ts";
import { web } from "./web.ts";
import type { WebThemeColors } from "./web.ts";

/** Custom property name (with the leading `--`) mapped to its CSS value. */
export type CssVariables = Record<string, string>;

/** Selector of the light theme (default). */
export const LIGHT_SELECTOR = ":root";

/** Selector of the dark theme: set `data-theme="dark"` on `<html>` or any ancestor. */
export const DARK_SELECTOR = '[data-theme="dark"]';

const GENERATED_HEADER =
  "/* Generated by packages/tokens/scripts/build-css.ts from src/. Do not edit. */";

/** Converts a token key such as `actionStrong` or `0.5` to kebab case (`action-strong`, `0-5`). */
export function toKebabCase(key: string): string {
  return key
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/\./g, "-")
    .toLowerCase();
}

/** Converts a leaf token value to CSS: numbers are lengths in px, strings pass through. */
export function toCssValue(value: string | number): string {
  return typeof value === "number" ? `${String(value)}px` : value;
}

/**
 * Flattens a nested token group into custom properties named `--<prefix>-<path>`.
 * @throws {TypeError} when a leaf is neither a string nor a number.
 */
export function flattenToCssVariables(group: object, prefix: string): CssVariables {
  const variables: CssVariables = {};
  const entries: [string, unknown][] = Object.entries(group);
  for (const [key, value] of entries) {
    const name = `${prefix}-${toKebabCase(key)}`;
    if (typeof value === "string" || typeof value === "number") {
      variables[name] = toCssValue(value);
    } else if (typeof value === "object" && value !== null) {
      Object.assign(variables, flattenToCssVariables(value, name));
    } else {
      throw new TypeError(`Token ${name} has an unsupported value type`);
    }
  }
  return variables;
}

/** Variables that change with the theme: semantic colors and web-only colors. */
export function themeVariables(theme: Theme, webColors: WebThemeColors): CssVariables {
  return {
    ...flattenToCssVariables(theme.color, "--color"),
    ...flattenToCssVariables(webColors, "--web"),
  };
}

/** Variables that do not change with the theme: scales, font, shadow, web sizes. */
export function sharedVariables(): CssVariables {
  return {
    ...flattenToCssVariables(radius, "--radius"),
    ...flattenToCssVariables(spacing, "--space"),
    "--font-family": font.cssStack,
    "--font-variant-numeric": font.tabularFigures,
    "--shadow-level-1": formatShadow(shadow.level1),
    ...flattenToCssVariables(web.control, "--web-control"),
    ...flattenToCssVariables(web.icon, "--web-icon"),
    ...flattenToCssVariables(web.layout, "--web-layout"),
    ...flattenToCssVariables(web.focus, "--web-focus"),
    ...flattenToCssVariables(web.typography, "--web-type"),
  };
}

function renderRule(selector: string, variables: CssVariables): string {
  const declarations = Object.entries(variables).map(([name, value]) => `  ${name}: ${value};`);
  return `${selector} {\n${declarations.join("\n")}\n}`;
}

/** Full contents of `dist/tokens.css`: light theme and shared values in `:root`, dark overrides after. */
export function renderTokensCss(): string {
  const light = { ...themeVariables(lightTheme, web.light), ...sharedVariables() };
  const dark = themeVariables(darkTheme, web.dark);
  return [
    GENERATED_HEADER,
    renderRule(LIGHT_SELECTOR, light),
    renderRule(DARK_SELECTOR, dark),
    "",
  ].join("\n");
}
